#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
snapshot_golden.py - export every CDM table of a database to CSV.

This module is the single implementation of "what a golden file looks like".
``tests/test_backward_compat.py`` imports it rather than reimplementing the
writer, so a baseline regenerated by the test and a baseline regenerated by this
script cannot diverge.

What changed in fix batch 6D (finding §4.2, batch 1 note 10)
-----------------------------------------------------------
``fact_resolution_log`` is now written (``DBLoader.load_resolutions`` became
reachable in this batch), and two columns had been exported verbatim that are
not behavioural:

* ``fact_resolution_log.log_id`` — an autoincrement surrogate, exactly like
  ``fact_concept_map.map_id``. Insertion order permutes it, so an unmasked
  baseline flips on every run. Masked.
* ``fact_concept_map.is_approved`` — masking it is not cosmetic. Since batch 1
  it is the *human* verdict and is three-state (NULL = nobody looked). Its value
  in an unreviewed database is always NULL, so exporting it verbatim pins
  nothing; masking it keeps the baseline from carrying a column whose only
  meaningful state is one no test can produce. The three-state semantics are
  pinned by ``tests/test_backward_compat.py``'s allowed-value map instead.

Both tables are also sorted by their natural key, ``(source_table,
source_column, source_value)``, so insertion order cannot change the diff.
``fact_resolution_log``'s unique key adds ``run_id``, which is masked; its
tie-breakers are therefore the *visible* columns, so the order is a function of
data the golden file actually contains.

What the golden writer normalises, and why
------------------------------------------
* Volatile columns (``loaded_at``, ``mapped_at``, ``run_id`` and friends) are
  blanked. They record when something happened, not what was decided, and a wall
  clock in a golden file fails every run.
* Surrogate keys whose value depends on insertion order rather than on pipeline
  behaviour are blanked (see above).
* Rows are sorted by primary key, or by the declared natural key where the
  surrogate is blanked. A permuted row order is not a behavioural change.
* Line endings are always ``\\n`` and the index is never written, so the file
  compares byte-for-byte across platforms.

Usage::

    python scripts/snapshot_golden.py --db-path vbd_cdm.db
    python scripts/snapshot_golden.py --db-path /tmp/cdm.db \\
        --output-dir /tmp/golden --prefix vectoratlas_

Module-level assumptions
------------------------
* ``sqlalchemy`` 2.x and ``pandas``; nothing else.
* The database is introspectable (SQLite file on disk, or a live connection).
"""

from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path
from typing import Dict, FrozenSet, List, Optional, Sequence, Tuple

import pandas as pd
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import Engine


logger = logging.getLogger(__name__)

PROJECT_ROOT: Path = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT_DIR: Path = PROJECT_ROOT / "tests" / "fixtures" / "golden"

#: Tables that make up the CDM. Anything else in the database (alembic's
#: bookkeeping table, quarantine tables left behind by consolidation) is
#: deliberately excluded.
CDM_TABLE_PREFIXES: Tuple[str, ...] = ("dim_", "fact_")

#: Columns that record *when* rather than *what*, plus per-run identities.
#: A `run_id` is a fresh timestamp-plus-hex value on every run, so leaving one
#: in a golden file would fail the very first comparison; `resolved_at` is the
#: ledger's write time for the same reason.
VOLATILE_COLUMNS: FrozenSet[str] = frozenset(
    {
        "loaded_at",
        "mapped_at",
        "applied_at",
        "reviewed_at",
        "resolved_at",
        "created_at",
        "updated_at",
        "run_id",
        "last_run_id",
    }
)

#: Surrogate keys that depend on insertion order rather than on behaviour, plus
#: the one column whose meaningful value no test can produce.
#:
#: ``fact_concept_map.is_approved`` is masked because it is the human verdict:
#: it is NULL for every row a run writes, and a NULL column in a baseline pins
#: nothing while making the file look like it pins something. Its three-state
#: semantics are asserted in ``tests/test_backward_compat.py``.
MASKED_COLUMNS: Dict[str, FrozenSet[str]] = {
    "fact_concept_map": frozenset({"map_id", "is_approved"}),
    "fact_resolution_log": frozenset({"log_id"}),
}

#: Natural keys used to sort tables whose surrogate key is masked. The first
#: three columns are the review's requirement (§4.2): insertion order must not
#: be able to change the diff. The trailing entries are *visible* tie-breakers
#: for ``fact_resolution_log``, whose unique key also contains the masked
#: ``run_id`` — so ties are broken by content the golden file actually holds.
SORT_KEYS: Dict[str, Tuple[str, ...]] = {
    "fact_concept_map": ("source_table", "source_column", "source_value"),
    "fact_resolution_log": (
        "source_table",
        "source_column",
        "source_value",
        "decision",
        "match_method",
        "concept_code",
        "match_score",
    ),
}


def render_csv(frame: pd.DataFrame) -> str:
    """
    Serialise ``frame`` to the exact text a golden file contains.

    Every writer in the project goes through this function so that a file
    produced by the script and a file produced by the test are byte-identical.
    """
    return frame.to_csv(index=False, lineterminator="\n", na_rep="")


def write_csv(frame: pd.DataFrame, path: Path) -> Path:
    """Write ``frame`` to ``path`` using :func:`render_csv`."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    # `newline=""` disables the platform newline translation that would
    # otherwise turn "\n" into "\r\n" on Windows.
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(render_csv(frame))
    return path


def list_cdm_tables(engine: Engine) -> List[str]:
    """Return the sorted names of every ``dim_*`` and ``fact_*`` table."""
    names = inspect(engine).get_table_names()
    return sorted(name for name in names if name.startswith(CDM_TABLE_PREFIXES))


def read_table(engine: Engine, table: str) -> pd.DataFrame:
    """
    Read one CDM table into a DataFrame.

    Raises
    ------
    ValueError
        If ``table`` is not a CDM table. The name is interpolated into SQL, so
        the prefix check is the guard against reading an unrelated table by
        accident.
    """
    if not table.startswith(CDM_TABLE_PREFIXES):
        raise ValueError(f"refusing to export a non-CDM table: {table!r}")
    with engine.connect() as connection:
        return pd.read_sql_query(text(f'SELECT * FROM "{table}"'), connection)


def primary_key_columns(engine: Engine, table: str) -> List[str]:
    """Return the primary-key columns of ``table``, in constraint order."""
    constraint = inspect(engine).get_pk_constraint(table)
    columns = constraint.get("constrained_columns") or []
    return [column for column in columns if column]


def canonicalise(
    frame: pd.DataFrame,
    table: str,
    sort_columns: Sequence[str],
) -> pd.DataFrame:
    """
    Blank volatile and surrogate columns, then order the rows deterministically.

    Parameters
    ----------
    frame : pandas.DataFrame
        The raw table contents.
    table : str
        Table name, used to look up :data:`MASKED_COLUMNS`.
    sort_columns : sequence of str
        Columns to order by. Unknown names are ignored, so a caller does not
        have to know the exact schema, and a column that a future migration
        removes does not turn every snapshot into an error.

    Returns
    -------
    pandas.DataFrame
        A new frame with a reset index.
    """
    canonical = frame.copy()

    masked = set(MASKED_COLUMNS.get(table, frozenset()))
    masked.update(column for column in canonical.columns if column in VOLATILE_COLUMNS)
    for column in sorted(masked):
        if column in canonical.columns:
            canonical[column] = None

    ordering = [column for column in sort_columns if column in canonical.columns]
    if ordering and not canonical.empty:
        # mergesort: stable, so rows that tie on every ordering column keep the
        # order they already had instead of being permuted by the sort.
        canonical = canonical.sort_values(ordering, kind="mergesort")
        canonical = canonical.reset_index(drop=True)

    return canonical


def snapshot_frame(engine: Engine, table: str) -> pd.DataFrame:
    """Read ``table`` and return it in canonical golden-file form."""
    frame = read_table(engine, table)
    sort_columns = list(SORT_KEYS.get(table) or primary_key_columns(engine, table))
    return canonicalise(frame, table, sort_columns)


def export_table(
    engine: Engine,
    table: str,
    output_dir: Path,
    prefix: str = "",
) -> Tuple[Path, int]:
    """
    Write one canonicalised table to ``<output_dir>/<prefix><table>.csv``.

    Returns
    -------
    tuple of (pathlib.Path, int)
        The path written and the number of data rows it contains.
    """
    frame = snapshot_frame(engine, table)
    path = write_csv(frame, Path(output_dir) / f"{prefix}{table}.csv")
    return path, len(frame)


def snapshot_database(
    engine: Engine,
    output_dir: Path,
    tables: Optional[Sequence[str]] = None,
    prefix: str = "",
) -> Dict[str, int]:
    """
    Export every CDM table to ``output_dir`` and log its row count.

    Parameters
    ----------
    engine : sqlalchemy.engine.Engine
        Connection to the database being snapshotted.
    output_dir : pathlib.Path
        Destination directory.
    tables : sequence of str, optional
        Restrict the export to these tables. Defaults to every CDM table.
    prefix : str, optional
        Prepended to each file name. The test harness uses ``<source>_`` to
        snapshot the cumulative database state after each source has run.

    Returns
    -------
    dict of str to int
        Mapping of table name to exported row count.
    """
    selected = list(tables) if tables is not None else list_cdm_tables(engine)
    counts: Dict[str, int] = {}

    for table in selected:
        path, rows = export_table(engine, table, Path(output_dir), prefix)
        counts[table] = rows
        logger.info(f"{table:<34s} {rows:>9d} rows -> {path}")

    return counts


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Command-line entry point. Returns a process exit status."""
    parser = argparse.ArgumentParser(
        description=(
            "Export every dim_* and fact_* table of a SQLite CDM database "
            "to canonical CSV files."
        ),
    )
    parser.add_argument(
        "--db-path",
        required=True,
        type=Path,
        help="Path to the SQLite database file to export.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help="Directory the CSVs are written to (default: tests/fixtures/golden/).",
    )
    parser.add_argument(
        "--prefix",
        default="",
        help=(
            "Prefix for every output file name. The regression test uses "
            "'<source>_' to snapshot the state after each source."
        ),
    )
    args = parser.parse_args(argv)

    logging.basicConfig(
        level=logging.INFO,
        stream=sys.stdout,
        format="%(asctime)s - %(name)s - %(levelname)s - %(message)s",
    )

    db_path: Path = Path(args.db_path).expanduser().resolve()
    if not db_path.is_file():
        logger.error(f"database file not found: {db_path}")
        return 1

    url = f"sqlite:///{db_path.as_posix()}"
    logger.info(f"exporting CDM tables from {url}")

    engine = create_engine(url)
    try:
        counts = snapshot_database(
            engine,
            Path(args.output_dir).expanduser(),
            prefix=args.prefix,
        )
    finally:
        engine.dispose()

    if not counts:
        logger.warning("no dim_* or fact_* tables were found in the database")
        return 0

    logger.info(
        f"exported {len(counts)} table(s), {sum(counts.values())} row(s) total"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())